CREATE OR REPLACE FUNCTION pg_temp.arreglar_tildes(p text) RETURNS text LANGUAGE plpgsql AS $f$
DECLARE r record; t text := p;
BEGIN
    IF t IS NULL OR position('?' IN t) = 0 THEN RETURN t; END IF;
    FOR r IN SELECT roto, bien FROM _tildes ORDER BY length(roto) DESC LOOP
        IF position(lower(r.roto) IN lower(t)) > 0 THEN
            -- la palabra entera (antes y después, nada que sea letra ni «?»); respeta mayúscula inicial
            t := regexp_replace(t, '(^|[^[:alpha:]?])' || replace(r.roto, '?', '\?') || '(?![[:alpha:]?])', '\1' || r.bien, 'g');
            t := regexp_replace(t, '(^|[^[:alpha:]?])' || replace(initcap(r.roto), '?', '\?') || '(?![[:alpha:]?])', '\1' || initcap(r.bien), 'g');
            t := regexp_replace(t, '(^|[^[:alpha:]?])' || replace(upper(r.roto), '?', '\?') || '(?![[:alpha:]?])', '\1' || upper(r.bien), 'g');
        END IF;
        EXIT WHEN position('?' IN t) = 0;
    END LOOP;
    -- el guion largo: «Plan Básico ? 17/12» → «Plan Básico — 17/12»
    t := replace(t, ' ? ', ' — ');
    RETURN t;
END $f$;

DO $$
DECLARE
    c record; n integer; total integer := 0;
BEGIN
    FOR c IN SELECT * FROM (VALUES
        ('planes', 'nombre'), ('planes', 'para_quien'),
        ('funciones', 'nombre'), ('funciones', 'menu'), ('funciones', 'grupo'),
        ('modulos', 'nombre'), ('modulos', 'descripcion'),
        ('permisos', 'descripcion'), ('permisos', 'area'),
        ('roles', 'nombre'), ('roles', 'descripcion'),
        ('cobros_ajustes', 'descripcion'), ('cobros_ajustes', 'transferencia_datos'), ('cobros_ajustes', 'prueba_detalle'),
        ('plataforma_ajustes', 'publica_razon_social'), ('plataforma_ajustes', 'publica_direccion')
    ) v(tabla, columna) LOOP
        IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = c.tabla AND column_name = c.columna) THEN
            EXECUTE format('UPDATE %I SET %I = pg_temp.arreglar_tildes(%I) WHERE position(''?'' IN %I) > 0 AND pg_temp.arreglar_tildes(%I) IS DISTINCT FROM %I',
                           c.tabla, c.columna, c.columna, c.columna, c.columna, c.columna);
            GET DIAGNOSTICS n = ROW_COUNT;
            IF n > 0 THEN RAISE NOTICE '092: %.% — % fila(s) arregladas', c.tabla, c.columna, n; END IF;
            total := total + n;
        END IF;
    END LOOP;
    RAISE NOTICE '092: tildes arregladas en % fila(s). Nada se borró.', total;
END $$;

